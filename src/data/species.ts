const byId = new Map(SPECIES_FORMS.map((f) => [f.id, f]))

export function getForm(id: string): SpeciesForm | undefined {
  return byId.get(id)
}

export function requireForm(id: string): SpeciesForm {
  const form = byId.get(id)
  if (!form) throw new Error(`Unknown form: ${id}`)
  return form
}

export function getAllForms(): SpeciesForm[] {
  return SPECIES_FORMS
}

export function getFormsByLine(lineId: string): SpeciesForm[] {
  return SPECIES_FORMS.filter((f) => f.speciesLineId === lineId)
}

export function getEggForms(): SpeciesForm[] {
  return SPECIES_FORMS.filter((f) => f.stage === 'egg')
}

/** Total discoverable encyclopedia entries (form × default color path; colors tracked separately) */
export function getEncyclopediaFormCount(): number {
  return SPECIES_FORMS.filter((f) => f.stage !== 'egg').length
}
